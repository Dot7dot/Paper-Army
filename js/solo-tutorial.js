// 單人模式的新手引導文案與階段設定。獨立於戰鬥模擬，避免影響雙人模式。
export const SOLO_STEPS = ['認識關卡', '佈置士兵', '畫出地形', '確認地形', '觀察戰鬥'];

export function soloLesson(level, levelIndex) {
  const first = levelIndex === 0;
  return {
    intro: first
      ? '歡迎來到紙上談兵！你不用操控士兵攻擊：先佈陣、再畫地形，開戰後小兵會自動前進。'
      : '這一關會沿用你已經學到的操作，請先觀察敵方陣容，再決定要帶哪些士兵。',
    deploy: first
      ? '① 點下方「劍士」選擇角色。② 點戰場左半邊放兵。③ 放好至少一隻後，按「下一步：畫地形」。'
      : '① 點選想派出的兵種。② 點戰場藍色左半邊部署；點已放的兵可以收回。③ 看好敵人配置，再繼續。',
    draw: first
      ? '① 建議先選「用手指畫」，最快完成第一次練習。② 從左到右畫一座低矮、平緩的山，線條可接到底部。③ 畫好按「完成」。'
      : '畫出符合本關戰術的地形。可以拍照、從相簿選圖，或直接用手指畫；不確定就用手指畫來練習。',
    adjust: '① 查看下方戰場預覽。② 確認有看到你畫的地面或山坡。③ 照片不準時拖曳四角、旋轉或調整深色閾值。④ 確認無誤再開戰。',
    battle: '戰鬥會自動進行！左上角是你的藍隊，右上角是紅色敵軍；你可以用「速度」加快觀看。獲勝才能解鎖下一關。',
    task: level.task?.text || '擊敗敵軍',
  };
}
